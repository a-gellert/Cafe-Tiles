local current = "en"

local function supported(lang)
	if not lang then return nil end
	lang = string.lower(string.sub(lang, 1, 2))
	if STRINGS[lang] then return lang end
	return nil
end

function M.detect()
	local info = sys.get_sys_info()
	return supported(info.device_language) or supported(info.language) or "en"
end

function M.set(lang)
	current = supported(lang) or "en"
end

function M.get_language()
	return current
end

function M.next_language()
	for i, l in ipairs(M.LANGS) do
		if l == current then return M.LANGS[i % #M.LANGS + 1] end
	end
	return "en"
end

function M.get(key, params)
	local text = STRINGS[current][key] or STRINGS.en[key] or key
	if params then
		for k, v in pairs(params) do
			text = string.gsub(text, "{" .. k .. "}", tostring(v))
		end
	end
	return text
end

return M
